/**
 * Retrieve verified anime/cartoon high-res poster and banner.
 * Uses exact match, normalized alphanumeric match, and stripped season/subtitle lookup
 * to prevent false negatives while strictly guarding against cross-anime collisions.
 */
export function getVerifiedAnimeImage(title?: string): VerifiedImageRecord | null {
  if (!title) return null;
  const raw = title.trim();
  if (!raw) return null;

  const lower = raw.toLowerCase();
  if (VERIFIED_ANIME_IMAGES[lower]) return VERIFIED_ANIME_IMAGES[lower];

  const clean = lower
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (VERIFIED_ANIME_IMAGES[clean]) return VERIFIED_ANIME_IMAGES[clean];

  const normKey = lower.replace(/[^a-z0-9]/g, '');
  if (!normKey || normKey.length < 3) return null;

  // 1. Strict match against normalized dictionary keys
  for (const [key, val] of Object.entries(VERIFIED_ANIME_IMAGES)) {
    const keyNorm = key.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (normKey === keyNorm) {
      return val;
    }
  }

  // 2. Strip common season/cour/part/episode suffixes and retry ONLY for exact matches (e.g. "Demon Slayer Season 4" -> "Demon Slayer")
  const strippedBase = lower
    .replace(/\b(season\s*\d+|s\d+|\d+(st|nd|rd|th)\s*season|part\s*\d+|cour\s*\d+|episode\s*\d+|ep\s*\d+|final\s*season|the\s*final\s*season|tv|the\s*animation|the\s*series)\b/gi, '')
    .replace(/[-:]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  if (strippedBase && strippedBase !== lower && strippedBase.length >= 3) {
    if (VERIFIED_ANIME_IMAGES[strippedBase]) return VERIFIED_ANIME_IMAGES[strippedBase];
    const strippedNorm = strippedBase.replace(/[^a-z0-9]/g, '');
    for (const [key, val] of Object.entries(VERIFIED_ANIME_IMAGES)) {
      const keyNorm = key.toLowerCase().replace(/[^a-z0-9]/g, '');
      if (strippedNorm === keyNorm) {
        return val;
      }
    }
  }

  return null;
}
