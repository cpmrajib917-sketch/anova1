/**
 * Generate a dynamic, unique SVG poster for any anime using its actual title.
 * Ensures that no anime ever displays another anime's artwork as a fallback!
 */
export function getDynamicAnimeFallbackPoster(title: string = 'Anime'): string {
  const cleanTitle = (title || 'Anime')
    .replace(/^toonstream-/i, '')
    .replace(/^moviebox-/i, '')
    .replace(/^anikoto-/i, '')
    .trim()
    .slice(0, 32);
  const initials = cleanTitle.split(/\s+/).slice(0, 2).map(w => w[0]).join('').toUpperCase() || 'A';
  let hash = 0;
  for (let i = 0; i < cleanTitle.length; i++) hash = (hash << 5) - hash + cleanTitle.charCodeAt(i);
  const hue1 = Math.abs(hash % 360);
  const hue2 = (hue1 + 65) % 360;

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="600" viewBox="0 0 400 600">
    <defs>
      <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="hsl(${hue1}, 70%, 14%)" />
        <stop offset="60%" stop-color="#070b16" />
        <stop offset="100%" stop-color="hsl(${hue2}, 75%, 10%)" />
      </linearGradient>
    </defs>
    <rect width="100%" height="100%" fill="url(#bg)" />
    <circle cx="200" cy="230" r="75" fill="hsl(${hue1}, 70%, 25%)" opacity="0.35" />
    <text x="200" y="255" font-family="system-ui, -apple-system, sans-serif" font-size="56" font-weight="900" fill="#00d2ff" text-anchor="middle">${initials}</text>
    <text x="200" y="380" font-family="system-ui, -apple-system, sans-serif" font-size="18" font-weight="800" fill="#ffffff" text-anchor="middle">${cleanTitle}</text>
    <text x="200" y="415" font-family="system-ui, -apple-system, sans-serif" font-size="11" font-weight="700" fill="#00d2ff" letter-spacing="3" text-anchor="middle">ANOVA ULTRA HD</text>
  </svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

